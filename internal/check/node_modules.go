package check

import (
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

const maxPackageManifestBytes = 1024 * 1024

func inspectNodeModules(repo string, installed map[string]map[string]bool) error {
	nodeModules := filepath.Join(repo, "node_modules")
	info, err := os.Lstat(nodeModules)
	if err != nil {
		if os.IsNotExist(err) {
			return nil
		}
		return err
	}
	if !info.IsDir() {
		return nil
	}

	return filepath.WalkDir(nodeModules, func(path string, entry os.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if !entry.IsDir() {
			return nil
		}

		name := entry.Name()
		if name == ".bin" {
			return filepath.SkipDir
		}
		if name == "node_modules" && path != nodeModules {
			return nil
		}
		if name == ".pnpm" {
			return nil
		}
		if strings.HasPrefix(name, ".") {
			return filepath.SkipDir
		}

		manifestPath := filepath.Join(path, "package.json")
		exists, err := regularFileExists(manifestPath, maxPackageManifestBytes)
		if err != nil {
			return err
		}
		if !exists {
			return nil
		}

		if err := addInstalledPackage(installed, manifestPath); err != nil {
			return err
		}
		return filepath.SkipDir
	})
}

func addInstalledPackage(installed map[string]map[string]bool, manifestPath string) error {
	content, exists, err := readRegularFile(manifestPath, maxPackageManifestBytes)
	if err != nil {
		return err
	}
	if !exists {
		return nil
	}

	var manifest struct {
		Name    string `json:"name"`
		Version string `json:"version"`
	}
	if err := json.Unmarshal(content, &manifest); err != nil {
		return fmt.Errorf("parse %s: %w", manifestPath, err)
	}
	addVersion(installed, manifest.Name, manifest.Version)
	return nil
}

func regularFileExists(path string, maxBytes int64) (bool, error) {
	info, err := os.Lstat(path)
	if err != nil {
		if os.IsNotExist(err) {
			return false, nil
		}
		return false, err
	}
	if !info.Mode().IsRegular() {
		return false, nil
	}
	if info.Size() > maxBytes {
		return false, fmt.Errorf("%s is too large: %d bytes exceeds %d", path, info.Size(), maxBytes)
	}
	return true, nil
}
